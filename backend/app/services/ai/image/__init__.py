"""Image providers.

Only the placeholder generator is implemented. A real provider (Replicate,
Stability, OpenAI images, Fal) is a single class implementing `ImageProvider`:
download the generated bytes and return them. Nothing else in the codebase
changes, because callers depend on the interface.
"""

from functools import lru_cache

from app.core.config import get_settings
from app.core.exceptions import ProviderError
from app.services.ai.base import ImageProvider
from app.services.ai.image.placeholder import PlaceholderImageProvider

__all__ = ["ImageProvider", "PlaceholderImageProvider", "get_image_provider"]


@lru_cache
def get_image_provider() -> ImageProvider:
    provider = get_settings().image_provider
    if provider == "mock":
        return PlaceholderImageProvider()
    raise ProviderError(
        f"IMAGE_PROVIDER={provider} is not implemented yet. Use IMAGE_PROVIDER=mock.",
        code="PROVIDER_NOT_IMPLEMENTED",
    )
